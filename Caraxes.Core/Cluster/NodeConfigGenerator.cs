using System.Text;
using YamlDotNet.Serialization;

namespace Caraxes.Core.Cluster;

/// <summary>
/// Generates one CamusDB <c>config.yml</c> per node, mounted read-only over the image's baked
/// <c>/app/Config/config.yml</c>. Node identity (name, id, host, ports, peers) stays in the
/// container's CAMUS_* environment — CLI flags outrank the file — so the file carries only what
/// the spec shapes: transaction defaults, sharding/query knobs, the <c>kahuna:</c> placement and
/// balancer section, and diagnostics. Only the zone differs between nodes.
/// </summary>
public static class NodeConfigGenerator
{
    /// <summary>In-container mount point of the per-node backup bind mount (see <see cref="ClusterSpec.Backups"/>).</summary>
    public const string BackupMount = "/backups";

    /// <summary>Where the node's backup catalog and artifacts live: <c>kahuna.backup_dir</c>.</summary>
    public const string BackupCatalogDir = BackupMount + "/catalog";

    /// <summary>The server-owned root every restore target must sit under: <c>kahuna.restore_root</c>.
    /// A sibling of the catalog, never inside it: a restore under the backup directory is refused.</summary>
    public const string BackupRestoreRoot = BackupMount + "/restore";

    public static string Generate(ClusterPlan plan, NodePlan node)
    {
        ClusterSpec spec = plan.Spec;

        // Ordered dictionaries keep the emitted file stable so run artifacts diff cleanly.
        Dictionary<string, object> kahuna = new()
        {
            ["replication_factor"] = spec.ReplicationFactor,
            ["enable_placement_rebalancer"] = spec.PlacementRebalancer,
            ["enable_leader_balancer"] = spec.LeaderBalancer,
        };

        if (node.Zone is not null)
            kahuna["zone"] = node.Zone;

        // Backups are off unless a directory is named. The three keys are the ones every node must
        // agree on; the PITR window and the retention knobs come through the passthrough below, so a
        // scenario states them next to the schedule that depends on them. See ClusterSpec.Backups.
        if (spec.Backups)
        {
            kahuna["backup_dir"] = BackupCatalogDir;
            kahuna["restore_root"] = BackupRestoreRoot;
            kahuna["backup_cluster_id"] = spec.Name;
        }

        // Spec-level passthrough last, so an explicit kahuna key in the spec wins over the
        // modeled fields if both name the same option.
        foreach ((string key, object value) in spec.Kahuna)
            kahuna[key] = value;

        Dictionary<string, object> root = new()
        {
            ["data_dir"] = "/data/",
            ["default_transaction_locking"] = spec.Locking,
            ["default_isolation_level"] = spec.Isolation,
            ["key_range_sharding"] = spec.KeyRangeSharding,
            ["distributed_query_execution"] = spec.DistributedQueryExecution,
            ["max_query_parallelism"] = spec.MaxQueryParallelism,
            ["kahuna"] = kahuna,
            ["diagnostics"] = new Dictionary<string, object>
            {
                ["enabled"] = spec.Diagnostics,
                ["prometheus_enabled"] = spec.Diagnostics,
            },
        };

        // Emitted only when the spec sets it, so the file stays identical for specs that predate
        // the option. Insertion order places it after the other transaction defaults.
        if (spec.ReadValidation.Length > 0)
        {
            Dictionary<string, object> ordered = new();
            foreach ((string key, object value) in root)
            {
                ordered[key] = value;
                if (key == "default_isolation_level")
                    ordered["default_read_validation"] = spec.ReadValidation;
            }
            root = ordered;
        }

        // Only when the spec turns it off, so configs from specs that predate the option stay identical.
        // The Raft port keeps its certificate either way; see ClusterSpec.Tls.
        if (!spec.Tls)
            root["grpc_tls_enabled"] = false;

        // Root-level passthrough last, so an explicit CamusDB key in the spec wins over the modeled
        // fields; the spec validator has already refused the keys that would replace a whole section.
        foreach ((string key, object value) in spec.Camusdb)
            root[key] = value;

        StringBuilder sb = new();
        sb.AppendLine($"# Generated by caraxes for cluster '{spec.Name}', node {node.Name}. Do not edit.");
        sb.Append(new SerializerBuilder().Build().Serialize(root));
        return sb.ToString();
    }
}
